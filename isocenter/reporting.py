"""The compliance report: its data, and its Markdown rendering."""
import datetime
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Protocol

#: What section 3.2 says became of an element the PHI scan could not
#: open. The `SCAN_GAP` row is written at ingest, before
#: `remove_private_tags` has been applied and long before any export, so
#: the row cannot say this and `generate_report` resolves it against the
#: object graph instead.
#:
#: Worded tenselessly on purpose. A report can be generated before any
#: export -- it then carries the boundary note but still renders
#: this section -- so "was exported" would be a claim about something
#: that may not have happened; what the graph actually settles is
#: whether the element is still there to be written, and
#: `remove_private_tags` is the only thing that removes it -- the
#: exporter applies no private filtering of its own.
GAP_REMOVED = "removed before export"
GAP_RETAINED = "retained for export"

#: No `element_tag` on the row, or no instance in the graph carrying
#: that UID -- a store written before the column existed, or an instance
#: whose UID was regenerated by `redact()`. Unresolved grades
#: REVIEW_REQUIRED: a disposition that cannot be established is not a
#: clean one.
GAP_UNRESOLVED = "unresolved"


# Not persisted, like `_actions_performed`: a stored copy would be a second
# answer to "what happened" beside the audit log, and could disagree with it.
@dataclass(frozen=True)
class PixelScanSummary:
    """What one `scan_pixel_content()` call did, for section 5.

    Recorded by the session on every exit of the call -- the early return
    with nothing configured to read, the normal return, and just before a
    `PixelScanError` -- and never persisted, so section 5 describes the
    scans of *this session* only, and says so.

    Attributes:
        serial_number (str, optional): The serial the call was restricted
            to, or None for every configured machine.
        attempted (int): Instances dispatched to OCR.
        read (int): Of those, instances at least one frame of which was
            read.
        unread (int): Instances that could not be read in full -- the
            length of `PhiReport.failures`.
        findings (int): Text regions found outside the configured zones.
        skipped (int): Instances not dispatched because their machine has
            no rule, or a rule with no zones.
    """
    serial_number: Optional[str]
    attempted: int
    read: int
    unread: int
    findings: int
    skipped: int


@dataclass(frozen=True)
class BurnedInTextSummary:
    """What one `burned_in_text` pass did, for section 5 (#1108).

    Session-local and never persisted, as `PixelScanSummary` is: a report
    over a reopened store does not describe an earlier session's pass,
    whose `REDACTION` row section 2 still counts.

    Also what one `export(check_burned_in=True)` read did (review of
    #1110): that read records nothing and skips nothing, so its `skipped`
    is 0, its `with_text` counts the instances it found text on, and its
    `acted` the instances it wrote a row for, withheld under `redact` and
    `withhold` and written under `report` (text found, or not read in
    full).

    Attributes:
        source (str): The call that ran it: `redact()`, or
            `_EXPORT_READ_SOURCE`.
        action (str): `report`, `redact` or `withhold`.
        attempted (int): Instances holding pixels (planned, for the
            export's read).
        read (int): Of those, read in this pass.
        unread (int): Could not be read in full.
        skipped (int): Already checked under this policy, not read again.
        with_text (int): Instances whose current record holds a box, or
            that the export's read found text on.
        regions (int): Boxes across them.
        acted (int): Redacted, reported or to be withheld, by action; for
            the export's read, withheld or written with a row.
    """
    source: str
    action: str
    attempted: int
    read: int
    unread: int
    skipped: int
    with_text: int
    regions: int
    acted: int


#: Closes section 5, after the grade basis and the metadata, PHI-scan and
#: pixel-scan lines, which each say what happened. This sentence claims
#: nothing about the run.
_METHODOLOGY_DISCLAIMER = (
    "This section records what the tooling was configured to do and what it "
    "logged doing -- whether the result meets HIPAA Safe Harbor, a Limited "
    "Data Set, or any other standard is a determination for the data "
    "steward, not for Isocenter.")


def _grade_basis_lines(report: "ComplianceReport") -> str:
    """Section 5's account of the grade, from the list the grade came from.

    A status other than PASS or REVIEW_REQUIRED renders as "not graded".

    Args:
        report (ComplianceReport): The report being rendered.

    Returns:
        str: The Grade Basis bullet, with one sub-bullet per review reason.
    """
    # `generate_report` grades PASS exactly when `review_reasons` is empty,
    # so rendering the list keeps this section from contradicting the grade.
    if report.validation_status == "PASS":
        return ("*   **Grade Basis:** PASS -- nothing recorded in sections 2 "
                "to 4 costs this run its PASS.\n")
    if report.validation_status != "REVIEW_REQUIRED":
        return f"*   **Grade Basis:** {report.validation_status} -- not graded.\n"
    lines = (f"*   **Grade Basis:** REVIEW_REQUIRED, for "
             f"{len(report.review_reasons)} reason(s):\n")
    for reason in report.review_reasons:
        lines += f"    *   {reason}\n"
    return lines


def _metadata_line(report: "ComplianceReport") -> str:
    """Whether the audit trail records a metadata remediation.

    Read from the audit rows, so a report over a reopened store still sees
    the remediation rows an earlier session wrote.

    Args:
        report (ComplianceReport): The report being rendered.

    Returns:
        str: The Metadata Remediation bullet.
    """
    # The same rows section 2 prints, so the two cannot disagree.
    if report.metadata_remediations:
        return (f"*   **Metadata Remediation:** {report.metadata_remediations} "
                "`REMEDIATION_*` row(s) in the audit trail (section 2) record "
                "tag values replaced, date-shifted or removed under the tag "
                "policy in force.\n")
    return ("*   **Metadata Remediation:** No `REMEDIATION_*` row is in the "
            "audit trail, so no metadata remediation is recorded.\n")


def _phi_scan_line(report: "ComplianceReport") -> str:
    """How many instances no PHI scan has seen at their current revision.

    Said on every report, with whether the instances it counts are graded.

    Args:
        report (ComplianceReport): The report being rendered.

    Returns:
        str: The PHI Scan bullet.
    """
    # The count is not a grade term of its own. Said on every report, so a
    # PASS over data no scan has read cannot pass for a PASS over data one
    # cleared. Whether those instances grade is one question with one
    # answer for all of them (#1064). In a store that holds a recorded
    # status, each is either stale (condition 8) or was never given a
    # status (condition 9), so every one is in the Grade Basis. In a store
    # that holds none, none of them is: no status means none is stale, and
    # condition 9 is gated on a recorded status so that a plain ingest ->
    # export conversion is not REVIEW_REQUIRED (Q3 on #573).
    line = (f"*   **PHI Scan (`audit()`):** {report.unscanned_instances} of "
            f"{report.total_instances} instance(s) have no PHI scan at their "
            "current revision.")
    if report.unscanned_instances and report.phi_status_recorded:
        line += (" Each was never scanned (grade condition 9) or was edited "
                 "after its scan (condition 8), and the Grade Basis counts "
                 "it.")
    elif report.unscanned_instances:
        line += (" No PHI status is recorded on any patient, study or "
                 "instance in this store, so they are not graded: an entity "
                 "never scanned costs the PASS only in a store that holds a "
                 "recorded status (grade condition 9).")
    return line + "\n"


def _pixel_scan_line(report: "ComplianceReport") -> str:
    """What `scan_pixel_content()` did in this session, one line.

    Args:
        report (ComplianceReport): The report being rendered.

    Returns:
        str: The Pixel Scan bullet, one clause per run.
    """
    # Names the method because `discover_redaction_zones()` also runs OCR,
    # and its failures reach section 4 too; a line that said only
    # "pixel scan" would read as contradicting a discovery row there.
    label = "*   **Pixel Scan (`scan_pixel_content()`):** "
    if not report.pixel_scans and report.burned_in_text_passes:
        # After a `burned_in_text` pass the old sentence would be false:
        # OCR did check burned-in text, by the line below (#1108).
        return (label + "No `scan_pixel_content()` ran in this session; the "
                "`burned_in_text` line below says what read burned-in text by "
                "OCR.\n")
    if not report.pixel_scans:
        return (label + "No `scan_pixel_content()` ran in this session, so "
                "this report does not say burned-in text was checked by OCR. "
                "A scan run by another session over this store is not "
                "described here.\n")
    runs = []
    for scan in report.pixel_scans:
        run = (f"read {scan.read} of {scan.attempted} instance(s), found "
               f"{scan.findings} text region(s) outside the configured "
               f"redaction zones, and {scan.unread} instance(s) could not be "
               f"read")
        if scan.serial_number:
            run += f" (restricted to serial {scan.serial_number})"
        if scan.skipped:
            run += (f"; {scan.skipped} instance(s) skipped because their "
                    f"machine has no configured redaction zones")
        runs.append(run)
    # Said whenever any run left an instance unread, because the unread
    # rows are permanent: a later run that reads the instance writes
    # nothing and removes nothing, so a session whose last scan was clean
    # still grades REVIEW_REQUIRED on the earlier row. Without this
    # sentence the Grade Basis above and a clean final run would read as a
    # contradiction.
    kept = ""
    if any(scan.unread for scan in report.pixel_scans):
        kept = (" Each instance a run could not read has a `WARNING` row in "
                "section 4, and a later run that reads it does not remove "
                "that row.")
    if len(runs) == 1:
        return label + f"ran once in this session: {runs[0]}.{kept}\n"
    numbered = "; ".join(f"run {i}: {run}" for i, run in enumerate(runs, 1))
    return (label + f"ran {len(runs)} times in this session -- "
            f"{numbered}.{kept}\n")


#: What a `burned_in_text` pass did to the instances it found text on, by
#: action, for section 5.
_BURNED_IN_TEXT_ACTED = {"redact": "redacted",
                         "report": "reported, not redacted",
                         "withhold": "to be withheld at export"}

#: The `source` of an `export(check_burned_in=True)` read's summary. Its
#: line says withheld or written, never `redacted`: the export redacts
#: nothing, under any action.
_EXPORT_READ_SOURCE = "export(check_burned_in=True)"


def _burned_in_text_line(report: "ComplianceReport") -> str:
    """What the `burned_in_text` passes of this session did, one line, or
    nothing when none ran (#1108).

    Args:
        report (ComplianceReport): The report being rendered.

    Returns:
        str: The Burned-in Text bullet, or "".
    """
    if not report.burned_in_text_passes:
        return ""
    runs = []
    for run in report.burned_in_text_passes:
        if run.source == _EXPORT_READ_SOURCE:
            done = "written" if run.action == "report" else "withheld"
            runs.append(
                f"{run.source} under action {run.action} read {run.read} of "
                f"{run.attempted} planned instance(s) holding pixels "
                f"({run.unread} could not be read) and found text on "
                f"{run.with_text} ({run.regions} region(s)); {run.acted} "
                f"{done}, with a row")
            continue
        runs.append(
            f"{run.source} under action {run.action} read {run.read} of "
            f"{run.attempted} instance(s) holding pixels ({run.skipped} "
            f"already checked, {run.unread} could not be read) and found text "
            f"on {run.with_text} ({run.regions} region(s)); {run.acted} "
            f"{_BURNED_IN_TEXT_ACTED[run.action]}")
    label = "*   **Burned-in Text (`burned_in_text`):** "
    tail = (" Text OCR did not find is not described here: OCR misses "
            "faint and short text, and reads text over anatomy in "
            "fragments.\n")
    if len(runs) == 1:
        return label + f"{runs[0]}.{tail}"
    numbered = "; ".join(f"pass {i}: {run}" for i, run in enumerate(runs, 1))
    return label + f"ran {len(runs)} times in this session -- {numbered}.{tail}"


@dataclass
class ComplianceReport:
    """
    Data Transfer Object holding all information required for a compliance report.

    Attributes:
        generated_at (datetime.datetime): Timestamp of generation.
        isocenter_version (str): Version of the system.
        project_name (str): Name of the session/project.
        privacy_profile (str): The profile that was actually applied, or a
            statement that none was.
        deid_method (str): Factual description of what was configured --
            profile, tag-rule count, pixel-rule count. Never the name of a
            compliance standard: whether the output satisfies one is a
            determination for the data steward.
        total_patients (int): Total patients processed.
        total_studies (int): Total studies processed.
        total_series (int): Total series processed.
        total_instances (int): Total instances processed.
        instances_written (int, optional): How many instances the last
            export in this session actually wrote. None when no export
            has run here -- which is not the same as zero, so the row is
            omitted rather than rendered as one.
        instances_requested (int, optional): How many that export asked
            for. `total_instances` counts the object graph, not delivered
            files.
        audit_summary (Dict[str, int]): Aggregated counts of audit actions.
        exceptions (list): List of error tuples (timestamp, action, details).
        data_losses (list): Elements present in the source and not in the
            output, as (timestamp, entity_uid, details, loss_scope).
        declined_remediations (list): Remediations that were proposed
            and did not run, as (timestamp, entity_uid, details). The
            value each one targeted is still in the object graph, so any
            one of these grades the run `REVIEW_REQUIRED`.
        scan_gaps (list): Elements the PHI scan could not open, as
            (timestamp, entity_uid, details, disposition). The
            disposition is one of `GAP_REMOVED`, `GAP_RETAINED` or
            `GAP_UNRESOLVED`, resolved by `generate_report` against the
            object graph, since the audit row is written at ingest.
        export_recorded (bool): Whether the audit log held an EXPORT
            row when the report was assembled. False renders the
            boundary note in the Executive Summary; it never moves the
            grade.
        validation_status (str): Overall status -- `PENDING` until a
            report is generated, then `PASS` or `REVIEW_REQUIRED`.
            Nothing emits `FAIL`: a run that fails raises rather than
            grading itself.
        review_reasons (List[str]): Why the run is not PASS, one entry
            per term of the grade -- empty exactly when it is PASS, because
            `generate_report` derives the grade from this list. Section 5
            renders it.
        metadata_remediations (int): `REMEDIATION_*` rows in the audit
            trail, the evidence section 5's metadata line reads.
        pixel_scans (List[PixelScanSummary]): Each `scan_pixel_content()`
            call made in this session, in order. Empty means none ran here,
            not that a scan found nothing.
        burned_in_text_passes (List[BurnedInTextSummary]): Each
            `burned_in_text` pass this session ran (#1108), in order.
        unacted_findings (Dict[str, int]): Patients, studies and instances
            reading IDENTIFIED when the report was assembled, keyed
            "patients", "studies", "instances": a finding the last PHI
            scan raised and no `anonymize()` pass since acted on. Any
            non-zero count grades the run `REVIEW_REQUIRED`.
        unscanned_instances (int): Instances with no PHI scan at their
            current revision -- never scanned, or edited since. Rendered
            in section 5 against `total_instances`. Not a grade term
            itself: grade conditions 8 and 9 count such an instance.
        never_scanned (Dict[str, int]): Patients, studies and instances on
            which no PHI status was ever recorded, keyed "patients",
            "studies", "instances". With `phi_status_recorded`, any
            non-zero count grades the run `REVIEW_REQUIRED` (condition 9);
            without it the counts are held and do not grade.
        phi_status_recorded (bool): Whether any patient, study or instance
            in the store held a recorded PHI status, stale or not, when
            the report was assembled. `generate_report` always sets it;
            the False of a report built by hand is a default, not a
            measurement.
    """
    generated_at: datetime.datetime = field(default_factory=datetime.datetime.now)
    isocenter_version: str = "Unknown"
    project_name: str = "Isocenter Session"

    # Configuration / Context
    privacy_profile: str = "Unknown"
    # Not a compliance claim, and never the name of a standard.
    # DicomSession.generate_report always passes a description derived
    # from the live configuration.
    deid_method: str = "Not recorded"

    # Cohort Statistics
    total_patients: int = 0
    total_studies: int = 0
    total_series: int = 0
    total_instances: int = 0

    # Export Delivery
    #
    # `total_instances` counts the graph, not the files written. These
    # two say what was written, and are None when this session has not
    # exported.
    instances_written: Optional[int] = None
    instances_requested: Optional[int] = None

    # Audit / Processing Statistics
    # e.g., {'ANONYMIZE_METADATA': 1200, 'REDACT_PIXELS': 50, 'EXPORT': 1200}
    audit_summary: Dict[str, int] = field(default_factory=dict)

    # Exceptions & Errors
    # List of "ERROR" or "WARNING" logs: (timestamp, action, details)
    exceptions: list = field(default_factory=list)

    # Data Loss
    # List of "DATA_LOSS" logs: (timestamp, entity_uid, details,
    # loss_scope), where loss_scope is PRIVATE, STANDARD, SIGNAL, or
    # None for a row written before the column existed.
    #
    # Its own field rather than more `exceptions`: nothing
    # failed, and an overlay dropped from an ordinary image belongs
    # nowhere near a section headed "Exceptions & Errors". The grade is
    # answered per row, on `loss_scope`, which is what lets the report
    # say *which* losses were graded rather than grading them alike.
    data_losses: list = field(default_factory=list)

    # Content that reached the exported file and that the PHI scan
    # could not open: (timestamp, entity_uid, details). Its own field
    # rather than more `data_losses` -- see get_audit_scan_gaps.
    scan_gaps: list = field(default_factory=list)

    # Remediations that were proposed and did not run, as (timestamp,
    # entity_uid, details): `REMEDIATION_DECLINED` rows. Its own
    # field for the same reason `scan_gaps` is: a third claim, not more
    # of either. 3.1 is content that is not in the export, 3.2 is
    # content that is and was never read, and this is content that was
    # read, was meant to be removed, and is still there.
    declined_remediations: list = field(default_factory=list)

    # Export Boundary
    #
    # True when the audit log held at least one EXPORT row as this
    # report was assembled. Keyed on the log rather than on a session
    # flag because the log survives a session reopened on an existing
    # store, and a per-process flag does not. False does not move the
    # grade -- a session that only audits is not wrong -- it makes the
    # renderer state the boundary: losses recorded during a later
    # export cannot appear here, and the same absent-row logic as
    # `instances_written` applies -- "not answered here", not "clean".
    export_recorded: bool = False

    # Validation
    # PENDING until graded; then PASS or REVIEW_REQUIRED. No FAIL --
    # see the class docstring.
    validation_status: str = "PENDING"
    review_reasons: List[str] = field(default_factory=list)

    # Section 5. Both are what happened, never what was configured.
    metadata_remediations: int = 0
    pixel_scans: List[PixelScanSummary] = field(default_factory=list)
    burned_in_text_passes: List["BurnedInTextSummary"] = field(default_factory=list)

    # Condition 7 of the grade: patients, studies and instances
    # reading IDENTIFIED, per level. Its reason line in `review_reasons`
    # is the rendering; this is the count behind it.
    unacted_findings: Dict[str, int] = field(default_factory=dict)
    # Instances with no PHI scan at their current revision. Section 5
    # says how many, so a PASS over data no scan has seen does not read
    # as a PASS over data a scan cleared.
    unscanned_instances: int = 0
    # Condition 9 of the grade (#1064): patients, studies and instances
    # with no recorded PHI status, per level, and the gate it grades
    # under -- whether the store holds a recorded status at all. Both
    # are kept, not one gated count: section 5's PHI Scan line needs the
    # gate to say whether the instances it counts are graded.
    never_scanned: Dict[str, int] = field(default_factory=dict)
    phi_status_recorded: bool = False


